import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";

interface AuthorizationCodeFlow {
  scopes?: { [scope: string]: unknown };
}

interface SecurityScheme {
  flows?: { authorizationCode?: AuthorizationCodeFlow };
}

interface SecurityRequirement {
  [scheme: string]: string[] | undefined;
}

interface Operation {
  operationId?: string;
  security?: SecurityRequirement[];
}

interface PathItem {
  [method: string]: unknown;
}

interface OpenApiSpec {
  paths: { [path: string]: PathItem };
  components?: { securitySchemes?: { [scheme: string]: SecurityScheme } };
}

const HTTP_METHODS = ["get", "put", "post", "delete", "patch", "head", "options", "trace"];

const projectRoot = fileURLToPath(new URL("..", import.meta.url));
const specPath = path.join(projectRoot, "openapi.yaml");
const outPath = path.join(projectRoot, "src", "generated", "security.ts");

const spec = parse(readFileSync(specPath, "utf8")) as OpenApiSpec;

const scheme = spec.components?.securitySchemes?.["uiAuth"];
if (scheme === undefined) {
  throw new Error("openapi.yaml: security scheme 'uiAuth' is missing from components.securitySchemes");
}
const declaredScopes = new Set(Object.keys(scheme.flows?.authorizationCode?.scopes ?? {}));
if (declaredScopes.size === 0) {
  throw new Error("openapi.yaml: security scheme 'uiAuth' declares no scopes");
}

const entries = new Map<string, string[]>();

for (const [routePath, pathItem] of Object.entries(spec.paths)) {
  for (const [method, rawOperation] of Object.entries(pathItem)) {
    if (!HTTP_METHODS.includes(method)) {
      continue;
    }
    const operation = rawOperation as Operation;
    const operationId = operation.operationId;
    if (typeof operationId !== "string" || operationId === "") {
      throw new Error(`openapi.yaml: ${method.toUpperCase()} ${routePath} has no operationId`);
    }
    if (entries.has(operationId)) {
      throw new Error(`openapi.yaml: duplicate operationId "${operationId}"`);
    }
    const security = operation.security ?? [];
    if (security.length === 0) {
      throw new Error(
        `openapi.yaml: operation "${operationId}" (${method.toUpperCase()} ${routePath}) declares no security — every endpoint must require uiAuth scopes`,
      );
    }
    if (security.length > 1) {
      throw new Error(
        `openapi.yaml: operation "${operationId}" uses multiple security alternatives (OR), which is not supported`,
      );
    }
    const requirement = security[0];
    const requirementKeys = requirement === undefined ? [] : Object.keys(requirement);
    if (requirementKeys.length !== 1 || requirementKeys[0] !== "uiAuth") {
      throw new Error(`openapi.yaml: operation "${operationId}" must require exactly the 'uiAuth' scheme`);
    }
    const scopes = (requirement?.["uiAuth"] ?? []).filter((scope) => typeof scope === "string");
    if (scopes.length === 0) {
      throw new Error(`openapi.yaml: operation "${operationId}" requires no scopes`);
    }
    for (const scope of scopes) {
      if (!declaredScopes.has(scope)) {
        throw new Error(`openapi.yaml: operation "${operationId}" requires undeclared scope "${scope}"`);
      }
    }
    entries.set(operationId, scopes);
  }
}

const lines = [...entries.entries()]
  .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
  .map(
    ([operationId, scopes]) =>
      `  ${JSON.stringify(operationId)}: [${scopes.map((scope) => JSON.stringify(scope)).join(", ")}],`,
  );

const content = `// Generated from openapi.yaml by scripts/generate-security.ts — do not edit;
// regenerated by \`npm run generate\` on every install/build/dev/typecheck.
import type { operations } from "./schema.js";

export const SCOPES_BY_OPERATION: Readonly<Record<keyof operations, readonly string[]>> = {
${lines.join("\n")}
};
`;

mkdirSync(path.dirname(outPath), { recursive: true });
writeFileSync(outPath, content, "utf8");
console.log(`generate-security: ${path.relative(projectRoot, outPath)} (${entries.size} operations)`);
